#!/usr/bin/env node
/**
 * Renders the Play Store link as an SVG QR code into src/generated/.
 *
 * Generated at build time with `qrencode` rather than drawn in the browser:
 * it is a handful of static paths, so shipping a QR library to every visitor
 * to redraw a constant would be wasteful.
 *
 *   yarn node scripts/gen-store-qr.mjs
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const appId = JSON.parse(readFileSync(resolve(root, 'capacitor.config.json'), 'utf8')).appId;
const url = `https://play.google.com/store/apps/details?id=${appId}`;

let svg;
try {
  // -m 0: no quiet zone; the component adds its own padding.
  svg = execFileSync('qrencode', ['-t', 'SVG', '-m', '0', '-s', '1', '-l', 'M', '-o', '-', url], {
    encoding: 'utf8',
  });
} catch {
  console.error('qrencode is not installed — install it or the QR will be missing.');
  process.exit(1);
}

// Keep only the dark modules. qrencode emits a white background rect first;
// recolouring that to currentColor would paint the whole code solid, so drop
// it and let the page background show through instead.
const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
const body = svg
  .replace(/^[\s\S]*?<svg[^>]*>/, '')
  .replace(/<\/svg>\s*$/, '')
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/<rect[^>]*fill="#?[Ff][Ff][Ff]+"[^>]*\/>/g, '')
  .replace(/style="fill:#?[0-9A-Fa-f]{3,6}[^"]*"/g, 'fill="currentColor"')
  .replace(/fill="#?[0-9A-Fa-f]{3,6}"/g, 'fill="currentColor"')
  .trim();

if (!viewBox) {
  console.error('Could not read a viewBox from qrencode output.');
  process.exit(1);
}

const outDir = resolve(root, 'src/generated');
mkdirSync(outDir, { recursive: true });

writeFileSync(
  resolve(outDir, 'storeQr.ts'),
  `// Generated by scripts/gen-store-qr.mjs — do not edit.
export const STORE_URL = ${JSON.stringify(url)};
export const STORE_QR_VIEWBOX = ${JSON.stringify(viewBox)};
export const STORE_QR_PATHS = ${JSON.stringify(body)};
`,
);

console.log(`QR for ${url}`);
console.log('  → src/generated/storeQr.ts');
